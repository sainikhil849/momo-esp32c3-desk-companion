"""Generate the embedded phone app header for each firmware variant."""
import gzip
import pathlib

here = pathlib.Path(__file__).resolve().parent
html = (here / "index.html").read_bytes()
gz = gzip.compress(html, compresslevel=9, mtime=0)
lines = ["// Generated by 3_Phone_App/make_webapp.py from 3_Phone_App/index.html - do not edit by hand.",
         "// The Momo phone app, gzipped (%d bytes -> %d bytes)." % (len(html), len(gz)),
         "const size_t WEBAPP_GZ_LEN = %d;" % len(gz),
         "const uint8_t WEBAPP_GZ[] PROGMEM = {"]
for i in range(0, len(gz), 20):
    lines.append("  " + ", ".join("0x%02x" % b for b in gz[i:i + 20]) + ",")
lines.append("};")
header = "\n".join(lines) + "\n"
project = here.parent
targets = (
    project / "2_Robot_ArduinoIDE" / "momo" / "webapp.h",
    project / "1_VSCode_Simulator" / "momo_wokwi" / "webapp.h",
    project / "1_VSCode_Simulator" / "momo_wokwi_no_wifi" / "webapp.h",
)

missing = [str(target.parent) for target in targets if not target.parent.is_dir()]
if missing:
    raise FileNotFoundError("Firmware target folder(s) not found: " + ", ".join(missing))

for target in targets:
    target.write_text(header, encoding="ascii")
    print("Updated %s" % target.relative_to(project))

print("%d bytes of HTML -> %d bytes gzipped" % (len(html), len(gz)))
